"""
Request/response schemas.

Now that we have the real column list from AIDS_Classification.csv:

    time, trt, age, wtkg, hemo, homo, drugs, karnof, oprior, z30, preanti,
    race, gender, str2, strat, symptom, treat, offtrt, cd40, cd420, cd80,
    cd820, infected

...PredictionRequest below has one explicit field per input column
(everything except `race`, which train.py already drops before fitting,
and `infected`, the target). This replaces the earlier Dict[str, float]
placeholder. Tightening it like this buys three things:

1. Real per-field validation instead of "whatever keys you sent".
2. `extra="forbid"` below - an unrecognized field (typo, or `race` sent
   by mistake) is now a clear 422 at the API boundary, not a silent
   no-op or a confusing downstream KeyError.
3. FastAPI's autogenerated /docs form now shows the actual 21 fields
   instead of an open-ended "additionalProp1/2/3" placeholder - which is
   exactly what caused the 400 you saw before you had real values to try.

All fields are typed float even though several (hemo, homo, drugs, z30,
gender, str2, symptom, treat, offtrt) are really 0/1 indicators. Kept
uniform on purpose: the model treats them as numeric either way.
"""

from typing import List

from pydantic import BaseModel, ConfigDict


class PredictionRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    trt: float
    age: float
    wtkg: float
    hemo: float
    homo: float
    drugs: float
    karnof: float
    oprior: float
    z30: float
    preanti: float
    gender: float
    str2: float
    strat: float
    symptom: float
    treat: float
    offtrt: float
    cd40: float
    cd420: float
    cd80: float
    cd820: float


class FeatureContribution(BaseModel):
    feature: str
    contribution: float


class PredictionResponse(BaseModel):
    probability_infected: float
    predicted_label: str
    top_features: List[FeatureContribution]

class ExplanationResponse(BaseModel):
    """Superset of PredictionResponse: same probability/label, but
    all_features instead of just top 5, plus base_value - the model's
    average predicted probability across the background sample, the
    starting point SHAP's contributions are measured from."""
    probability_infected: float
    predicted_label: str
    base_value: float
    all_features: List[FeatureContribution]


class ModelRun(BaseModel):
    model_name: str
    accuracy: float
    recall_infected: float
    params: dict[str, str]